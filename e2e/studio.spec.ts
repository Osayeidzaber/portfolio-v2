test("invoice recovery is opt-in, restores incomplete typing and clears on sign out", async ({ page, baseURL }, info) => {
  const secret = process.env.SESSION_SECRET || ""
  test.skip(secret.length < 32, "An admin session secret is required for authenticated browser QA.")
  test.skip(Boolean(process.env.STUDIO_DATA_REPO && process.env.STUDIO_GITHUB_TOKEN), "Do not touch connected invoice storage during browser QA.")
  if (info.project.name === "mobile") await page.setViewportSize({ width: 375, height: 812 })
  page.on("dialog", (dialog) => dialog.accept())
  await page.context().addCookies([{ name: SESSION_COOKIE, value: createToken(secret), url: baseURL! }])
  await page.goto("/admin/oz-studio")
  await page.getByRole("button", { name: "Open PDF designer", exact: true }).click()
  await expect(page.getByLabel("Keep a recovery copy on this device", { exact: true })).not.toBeChecked()
  await page.getByLabel("Project / invoice title", { exact: true }).fill("Recover this unfinished invoice")
  expect(await page.evaluate(() => localStorage.getItem("oz.invoice.recovery.v1:new"))).toBeNull()
  await page.getByLabel("Keep a recovery copy on this device", { exact: true }).check()
  await page.getByLabel("Client email", { exact: true }).fill("unfinished@")
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("oz.invoice.recovery.v1:new") || "null")?.fields.client.email)).toBe("unfinished@")
  await page.reload()
  await page.getByRole("button", { name: "Open PDF designer", exact: true }).click()
  await page.getByRole("button", { name: "Restore typing", exact: true }).click()
  await expect(page.getByLabel("Project / invoice title", { exact: true })).toHaveValue("Recover this unfinished invoice")
  await expect(page.getByLabel("Client email", { exact: true })).toHaveValue("unfinished@")
  await expect(page.getByRole("button", { name: "Open PDF viewer ↗", exact: true })).toBeDisabled()
  await page.getByRole("button", { name: "Sign out", exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/login$/)
  expect(await page.evaluate(() => localStorage.getItem("oz.invoice.recovery.v1:new"))).toBeNull()
})
